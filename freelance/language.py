"""Определяет украинский язык объявления по словам автора заказа."""
import re

UKRAINIAN_REASON = "language:uk"


# Короткие технические заголовки часто состоят из общих слов («бот», «сайт», «для»).
# Различимые формы учитываем и без уникальных букв: «Шукаю розробника», «Створити бота».
_UK = re.compile(
    r"^(?:потріб|необхід|шука[юєт]|пошук|розроб|створ(?:и|ю|ен)|зроби|доробити|написати|налашту|"
    r"налаштов|завдан|замовл|виконав|виконат|обробк|даних$|збирати|завантаж|"
    r"побуду|зробл|допомог|працю|отрим|посилан|вимог|термін|вартіст|оплатою|"
    r"додаток$|додатк|знайти|фахів|запит(?:и|ів|у)?$|можливіст|опрацю|"
    r"зручн|підключ|має$|який$|щоб$|щодо$|дохід|досвід|напишіть|користувач|використ|"
    r"перенесення|сповіщ|повідомлен|сторін(?:к|ок$)|переклад(?:у|ом|ів)?$|платіж|обмін|облік|застосун|доопрац|"
    r"вивантаж|звіт|збір|пошти$|товарів$|таблиці$|дані$)|(?:заці[яїю]|істю|івський)$"
)
# В русском «помочь магазину» и «добавить сайту» естественны. Смысл даёт сочетание слов.
_UK_PHRASE = re.compile(
    r"\b(?:для\s+(?:магазину|друку|сайту)|дизайн\s+сайту|(?:адаптивного|нового)\s+лендингу)\b", re.I
)
_RU = re.compile(
    r"^(?:нуж[еон]|необход|требу|ищу$|ищем$|разраб|созда|сдела|доработ|написать|"
    r"настро|настра|задани|заказ|исполн|обработ|данных$|собра|получ|добав|"
    r"помо[чг]|работ|ссылк|стоимост|требован|таблицу$|котор|чтобы$|техническ|"
    r"заявк|системы$|задач|пользовател|приложен|получени|информ|установить$)"
)
_WORD = re.compile(r"[а-яёіїєґў]+", re.I)
_QUOTE = re.compile(r'«[^»]*»|“[^”]*”|„[^“]*“|"[^"]*"')
_URL = re.compile(r"https?://\S+|www\.\S+", re.I)


def _signals(text: str) -> tuple[int, int]:
    uk = 2 * len(_UK_PHRASE.findall(text))
    ru = 0
    for word in _WORD.findall(text.lower()):
        if word.startswith(("україн", "київ", "львів")):
            continue
        if _UK.search(word):
            uk += 2
        elif _RU.match(word):
            ru += 2
        elif word in ("треба", "можна", "є") or (len(word) > 1 and any(letter in word for letter in "іїєґ")):
            uk += 1
        elif any(letter in word for letter in "ыэёъ"):
            ru += 1
    return uk, ru


def is_ukrainian(title: str | None, body: str | None) -> bool:
    text = _URL.sub(" ", f"{title or ''}\n{body or ''}")
    # Название товара и пример текста интерфейса могут быть на другом языке.
    # Если весь содержательный текст заключён в кавычки, учитываем и его.
    uk, ru = _signals(_QUOTE.sub(" ", text))
    if not (uk or ru):
        uk, ru = _signals(text)
    return uk >= 2 and uk > ru
